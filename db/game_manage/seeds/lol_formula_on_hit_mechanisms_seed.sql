-- =============================================================================
-- LoL generic-formula on-hit mechanisms batch seed
-- （Kog'Maw W 预开启 / Teemo E 即时 / 纳什 / 界弓 / 破舰者远程近似 / 巨型九头蛇远程主目标）
-- =============================================================================
--
-- 目标：在 Batch-B 普攻闭环、Batch-C 装备实体，以及 teemo/kogmaw 普攻
--       emit_event(event/basic_attack_hit) 已就绪之上，幂等挂载六个独立
--       passive provider（英雄两项 + 装备四项），统一 ALL-match
--       event/basic_attack_hit(20211) + event/source_owner(20212)，
--       max_triggers_per_event=1，经 listener_effect_sequences 运行各自 effect sequence。
--
-- 范围（机制边界）：
-- 1. hero_kogmaw W 预开启 rank5 baseline：
--    magic = event.entry_target.attr.hp.max * 0.06；
--    只表示预开启 on-hit；不建主动开启、8 秒到期、射程。
-- 2. hero_teemo E rank5 即时部分：
--    magic const 65；不录持续伤害与叠层刷新，不加 AP 系数。
-- 3. item_3115 纳什之牙：
--    magic = 15 + event.entry_source.attr.ap.resolved * 0.15。
-- 4. item_3302 界弓：
--    magic const 30；不录光暗交替、双抗、穿透。
-- 5. item_3181 破舰者远程近似：
--    provider_target state hullbreaker_hits（缺省 0）；
--    每次：add 1 → condition >=5 physical damage → 同 condition reset 0；
--    damage = event.entry_source.attr.ad.base * 0.84
--           + event.entry_source.attr.hp.max * 0.035。
--    0.84 / 0.035 为补充远程近似系数：DataDragon 16.9.1 未提供该数值，
--    本 seed 不宣称版本精确。
-- 6. item_3748 巨型九头蛇远程主目标：
--    physical = event.entry_source.attr.hp.max * 0.005；
--    不录后方锥形范围伤害、主动劈砍；0.005 为补充远程近似，同上不宣称版本精确。
--
-- live formula 路径只使用 ad / ap / hp 词根（如 attr.ad.base、attr.ap.resolved、
-- attr.hp.max）；不得使用旧版 AD/AP 全名路径，也不得引用 ability 参数路径。
--
-- 契约要点：
-- 1. 单事务；固定 game_id='lol'；先 ensure_game_partitions，再锁定 game_data_state。
-- 2. 候选 revision = locked current_revision + 1；仅业务数据实际插入/变化时推进。
-- 3. 六个实体、teemo/kogmaw basic_attack_hit emit、所需 reserved_type、
--    hp/ad/ap attribute_definitions 缺失则 RAISE EXCEPTION 回滚。
-- 4. 六个 provider 相互独立；英雄 provider 不挂装备，装备 provider 不挂英雄。
-- 5. Kog/Teemo 以 always-on passive provider 表达；不新建 dedicated ability/phase。
-- 6. 不自动 publish；不做 DELETE；不写 legacy Bundle/Catalog/skill 表。
-- 7. 预计 fresh write 约 68 业务行（6 provider / 6 mount / 6 listener / 12 matcher /
--    6 listener_effect_sequences / 6 sequence / 8 step / 1 state_field / 9 formula /
--    8 detail）；types 投影同值不计入 material change。
--
-- 前置：reserved_types_seed.sql；lol_batch_b_adc_entities_seed.sql；
--       lol_batch_c_adc_items_seed.sql；
--       lol_adc_item_on_hit_passives_seed.sql（或等价 teemo/kogmaw emit 已存在）。

BEGIN;

DO $$
DECLARE
    v_game_id            varchar(64) := 'lol';
    v_locked_current     bigint;
    v_candidate          bigint;
    v_changed            boolean := false;
    v_rowcount           integer;
    v_missing_reserved   text;
    v_missing_entity     text;
    v_missing_attr       text;
    v_required_reserved  int[] := ARRAY[
        20100, -- value_type/number
        20110, -- selector/self
        20111, -- selector/opponent
        20120, -- provider_kind/passive
        20150, -- operation/damage
        20160, -- operation/state_change
        20170, -- value_policy/add
        20172, -- value_policy/override
        20181, -- match_mode/all
        20211, -- event/basic_attack_hit
        20212, -- event/source_owner
        20220, -- damage/physical
        20221, -- damage/magic
        20252  -- state_scope/provider_target
    ];
