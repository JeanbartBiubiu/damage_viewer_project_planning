            ('hero_kogmaw'),
            ('hero_teemo'),
            ('item_3115'),
            ('item_3181'),
            ('item_3302'),
            ('item_3748')
           ) AS req(entity_id)
     WHERE NOT EXISTS (
               SELECT 1
                 FROM public.game_entities ge
                WHERE ge.game_id = v_game_id
                  AND ge.entity_id = req.entity_id
           );
    IF v_missing_entity IS NOT NULL THEN
        RAISE EXCEPTION
            'lol_formula_on_hit_mechanisms_seed: missing game_entities (Batch-B/C prerequisite): %',
            v_missing_entity;
    END IF;

