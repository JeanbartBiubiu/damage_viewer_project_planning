    IF NOT EXISTS (
        SELECT 1
          FROM public.effect_steps st
          JOIN public.event_effect_details ed
            ON ed.game_id = st.game_id
           AND ed.step_id = st.step_id
         WHERE st.game_id = v_game_id
           AND st.step_id = 'step_hero_teemo_basic_attack_emit_hit'
           AND st.sequence_id = 'sequence_hero_teemo_basic_attack_damage'
           AND st.operation_type_id = 20158
           AND ed.event_type_id = 20211
    ) THEN
        RAISE EXCEPTION
            'lol_formula_on_hit_mechanisms_seed: missing hero_teemo basic_attack_hit emit (on-hit passives prerequisite)';
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM public.effect_steps st
          JOIN public.event_effect_details ed
            ON ed.game_id = st.game_id
           AND ed.step_id = st.step_id
         WHERE st.game_id = v_game_id
           AND st.step_id = 'step_hero_kogmaw_basic_attack_emit_hit'
           AND st.sequence_id = 'sequence_hero_kogmaw_basic_attack_damage'
           AND st.operation_type_id = 20158
           AND ed.event_type_id = 20211
    ) THEN
        RAISE EXCEPTION
            'lol_formula_on_hit_mechanisms_seed: missing hero_kogmaw basic_attack_hit emit (on-hit passives prerequisite)';
    END IF;

