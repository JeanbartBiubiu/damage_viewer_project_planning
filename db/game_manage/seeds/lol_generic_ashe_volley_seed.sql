--       Volley：55 mana、4000ms CD、impact 对 opponent 恰好一次 physical damage =
--       200 + 1.0 * (source.attr.ad.resolved - source.attr.ad.base)。
--       Wiki 写明 rank-5 发射 11 箭，但被多箭命中的敌人仅受第一箭伤害；
--       本 seed 在 1v1 语义下只建模一次伤害实例（不做 per-arrow 循环）。
--
-- 契约要点：
-- 1. 单事务；固定 game_id='lol'；先 ensure_game_partitions，再锁定 game_data_state。
-- 2. 候选 revision = locked current_revision + 1；仅业务数据实际插入/变化时推进。
-- 3. 必需 game / reserved_type / attribute_definitions(hp,mana,ad,attack_speed,
--    armor,magic_resist,hp_regen,mana_regen) 缺失则 RAISE EXCEPTION 回滚。
-- 4. 自包含 ensure hero_ashe 实体 + level-1 面板 + mana 资源（280/280）；
--    仅 mount 独立 provider_hero_ashe_w_volley。与既有
--    provider_hero_ashe_rangers_focus（Q / 普攻 Focus-Flurry）并存：不 DELETE、
--    不 UPDATE、不覆盖该 provider 及其 ability/state/effect 行。
-- 5. 不自动 publish；不做 DELETE/DROP/CASCADE/DDL；不写 legacy Bundle/Catalog。
--
-- 明确排除（本脚本不建模）：
--   Frost Shot 减速 / 控制态；箭矢飞行 / 锥形几何 / 碰撞 / 距离 / 多目标选取；
--   per-arrow 循环；其它 rank；Q/E/R；普攻图改写；live migration；自动 publish。
--
-- 数值来源（League Wiki Template:Data Ashe/Volley；注释引用，无运行时外部依赖；
-- 无截图 / OCR 溯源）：
--   revision id 4007430
--   content SHA256 7e12c2b27533ff696411e2eff05d7f5b5c9e3b1ad45f09e017df2a764abb5e28
--   reviewed contract path：
--     数据参考/lol-wiki-current-champions/normalized/reviewed-contracts.json#ashe-w
--   rank-5：physical 200 + 100% bonus AD；mana 55；cooldown 4000ms；11 arrows，
--   多箭命中同一敌人仅计第一箭伤害。
--   英雄 level-1 面板（与 Ashe Q seed 对齐）：hp610 mana280 ad59 AS0.658
--   armor26 MR30 hpregen3.5 manaregen7。
--
-- 前置：reserved_types_seed.sql；所需 attribute_definitions 已存在。
