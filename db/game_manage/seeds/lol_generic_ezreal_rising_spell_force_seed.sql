--
-- 目标：幂等挂载 hero_ezreal 独立 passive provider，表达 Rising Spell Force：
--       每次成功非普攻技能命中（本合同确定性 1v1 driver 范围：每次调度的
--       非普攻 ability cast 视为对唯一目标一击）叠 1 层；
--       max 5 / 6000ms / refresh_duration（refresh-on-write）；
--       AS percent_add = 0.10 * provider.state.rising_spell_force_stacks
--       （满层上限 0.50）。
--
-- 契约要点：
-- 1. 单事务；固定 game_id='lol'；先 ensure_game_partitions，再锁定 game_data_state。
-- 2. 候选 revision = locked current_revision + 1；仅业务数据实际插入/变化时推进。
-- 3. 必需 game / Batch-B hero_ezreal / attribute_definitions(attack_speed) /
--    reserved_type 缺失则 RAISE EXCEPTION 回滚。
-- 4. 仅 mount 独立 provider_hero_ezreal_rising_spell_force 到 hero_ezreal；
--    不重建 / 不覆盖 Batch-B 实体面板、普攻 provider、其它 provider；
--    不创建 Ezreal Q/W/E/R ability 定义或 hit producer。
-- 5. provider listener：event/ability_started + event/source_owner（ALL match），
--    ability_id 未绑定（NULL）；sole effect = state_change add +1 stack。
--    普攻不加层：canonical runtime 仅对 TypeSet 排除 ability/basic_attack 的
--    top-level ability 合成 event/ability_started。
-- 6. 不自动 publish；不做 DELETE/DROP/CASCADE/DDL；不写 legacy Bundle/Catalog。
--
-- 明确排除 / 范围边界（本脚本不建模 / 不宣称）：
--   未命中（miss）；多目标；单次 cast 多段 hit；Q/W/E/R 技能本体；
--   普攻图改写；其它被动；live migration；自动 publish；single_attacker_dps。
--   当前 scope 将每次调度的非普攻 Ezreal ability cast 视为对唯一 1v1 目标
--   一击——这是显式确定性边界，不是生产命中语义。
--
-- 数值来源（League Wiki Template:Data Ezreal/Rising Spell Force；注释引用，
-- 无运行时外部依赖；截图 / OCR 不是数值溯源）：
--   revision id 3932280
--   content SHA256 5996c969e2d1b53b3c805737fa161b4a9e235d6e7b7c74899a6580de34ca77ba
--   reviewed contract path：
--     C:\project\damage_wasm_dev\数据参考\lol-wiki-current-champions\normalized\reviewed-contracts.json#ezreal-p
--   每层 AS +10%（percent_add 0.10）；最多 5 层（上限 +50%）；持续 6000ms；
--   后续命中/写入刷新时长。
--
-- 前置：reserved_types_seed.sql；Batch-B hero_ezreal；attack_speed 属性定义。
-- 建议发布版本（本脚本不负责 publish）：
--   lol-generic-ezreal-rising-spell-force-v1-20260717

