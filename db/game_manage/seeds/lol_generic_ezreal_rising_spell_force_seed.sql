            'rising_spell_force_stacks_add',
            '{"op":"const","value":1}'::jsonb,
            v_candidate,
            NOW()
        ),
        (
            v_game_id,
            'provider_hero_ezreal_rising_spell_force',
            'rising_spell_force_attack_speed',
            '{"op":"mul","args":[{"op":"const","value":0.10},{"op":"read","path":"provider.state.rising_spell_force_stacks"}]}'::jsonb,
            v_candidate,
            NOW()
        )
    ON CONFLICT (game_id, provider_id, formula_key) DO UPDATE SET
        expression = EXCLUDED.expression,
        change_revision = EXCLUDED.change_revision,
        updated_at = NOW()
